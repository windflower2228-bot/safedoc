// ─── 키워드 → 적용 가능한 별표2 항목 매핑 함수 ─────────────────────
export function matchDutiesByKeywords(keywords: string[]): SupervisorDutyItem[] {
  if (!keywords || keywords.length === 0) return []
  const lower = keywords.map(k => k.toLowerCase())
  return SUPERVISOR_DUTY_TABLE.filter(item =>
    item.keywords.some(kw =>
      lower.some(lk => lk.includes(kw) || kw.includes(lk))
    )
  )
}

// 위험성평가 텍스트에서 작업유형 키워드 추출
export function extractWorkKeywords(text: string): string[] {
  const allKw = SUPERVISOR_DUTY_TABLE.flatMap(d => d.keywords)
  const found = new Set<string>()
  const t = text.toLowerCase()
  for (const kw of allKw) {
    if (t.includes(kw)) found.add(kw)
  }
  return Array.from(found)
}

